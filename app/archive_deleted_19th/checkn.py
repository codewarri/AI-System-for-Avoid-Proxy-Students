def TrackImages():
    check_haarcascadefile()
    assure_path_exists("Attendance/")
    assure_path_exists("StudentDetails/")
    assure_path_exists("UnauthorizedImages/") 
    for k in tv.get_children():
        tv.delete(k)

    recognizer = cv2.face.LBPHFaceRecognizer_create()
    exists3 = os.path.isfile("TrainingImageLabel/Trainner.yml")
    if exists3:
        recognizer.read("TrainingImageLabel/Trainner.yml")
    else:
        mess._show(title='Data Missing', message='Please click on Save Profile to reset data!!')
        return

    harcascadePath = "haarcascade_frontalface_default.xml"
    faceCascade = cv2.CascadeClassifier(harcascadePath)

    cam = cv2.VideoCapture(0)
    font = cv2.FONT_HERSHEY_SIMPLEX
    col_names = ['Id', '', 'Name', '', 'Date', '', 'Time']
    exists1 = os.path.isfile("StudentDetails/StudentDetails.csv")
    if exists1:
        df = pd.read_csv("StudentDetails/StudentDetails.csv")
    else:
        mess._show(title='Details Missing', message='Students details are missing, please check!')
        cam.release()
        cv2.destroyAllWindows()
        window.destroy()

    attendance_set = set()  # To avoid duplicate entries during the session

    while True:
        ret, im = cam.read()
        gray = cv2.cvtColor(im, cv2.COLOR_BGR2GRAY)
        faces = faceCascade.detectMultiScale(gray, 1.2, 5)
        for (x, y, w, h) in faces:
            cv2.rectangle(im, (x, y), (x + w, y + h), (225, 0, 0), 2)
            serial, conf = recognizer.predict(gray[y:y + h, x:x + w])
            if conf < 50:
                ts = time.time()
                date = datetime.datetime.fromtimestamp(ts).strftime('%d-%m-%Y')
                timeStamp = datetime.datetime.fromtimestamp(ts).strftime('%H:%M:%S')
                aa = df.loc[df['SERIAL NO.'] == serial]['NAME'].values
                ID = df.loc[df['SERIAL NO.'] == serial]['ID'].values
                ID = str(ID).strip("[]")
                bb = str(aa).strip("[]").strip("'")
                attendance = (ID, bb, date, timeStamp)

                if ID not in [att[0] for att in attendance_set]:  # Check for duplicates
                    attendance_set.add(attendance)
                    with open(f"Attendance/Attendance_{date}.csv", 'a+') as csvFile1:
                        writer = csv.writer(csvFile1)
                        writer.writerow([ID, '', bb, '', date, '', timeStamp])
            else:
                Id = 'Unknown'
                timestamp = datetime.datetime.now().strftime("%Y%m%d%H%M%S")
                unknown_img_path = f"UnauthorizedImages/Unknown_{timestamp}.jpg"
                cv2.imwrite(unknown_img_path, im[y:y+h, x:x+w])

            cv2.putText(im, str(bb if conf < 50 else "Unknown"), (x, y + h), font, 1, (255, 255, 255), 2)

        cv2.imshow('Taking Attendance', im)
        if cv2.waitKey(1) == ord('q'):
            break

    for att in attendance_set:
        tv.insert('', 0, text=att[0], values=(att[1], att[2], att[3]))

    cam.release()
    cv2.destroyAllWindows()


